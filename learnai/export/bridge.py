"""The notebook -> interactive-page bridge.

This is what keeps the two halves of the repo honest. The interactive pages under
`interactive/` do not invent their numbers: a notebook trains a real model, dumps
real tensors through this module, and the page renders *those*. When you change
the model, you re-export and the page changes with it.

    from learnai.export import export_attention
    export_attention(attn, tokens, "interactive/attention/data/shakespeare.json")

Everything is written as plain JSON — no msgpack, no base64 — so you can open the
file and read it. Floats are rounded to keep files small and diffs legible.
"""

from __future__ import annotations

import json
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

import numpy as np

PRECISION = 4  # decimals kept in exported floats


def _to_list(x: Any, precision: int = PRECISION):
    """Tensor / ndarray / scalar -> nested plain Python lists, rounded."""
    if hasattr(x, "detach"):  # torch.Tensor
        x = x.detach().cpu().numpy()
    if isinstance(x, np.ndarray):
        if np.issubdtype(x.dtype, np.floating):
            return np.round(x.astype(np.float64), precision).tolist()
        return x.tolist()
    if isinstance(x, Mapping):
        return {k: _to_list(v, precision) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [_to_list(v, precision) for v in x]
    if isinstance(x, (np.bool_, bool)):
        return bool(x)
    if isinstance(x, (np.floating, float)):
        return round(float(x), precision)
    if isinstance(x, (np.integer, int)):
        return int(x)
    return x


def write_json(payload: dict, path: str | Path, verbose: bool = True) -> Path:
    """Write a payload, creating parent directories. Returns the path.

    If `path` ends in `.js`, the JSON is wrapped as an assignment into
    `window.LEARNAI_DATA[<stem>]`. That matters: browsers block `fetch()` of a
    local file, so a page opened straight off disk cannot read a `.json` — but a
    `<script src="data/foo.js">` tag loads fine. Writing `.js` is what lets the
    interactive pages work without running a server.
    """
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    # NaN and Infinity are accepted by Python's encoder but are not valid JSON.
    # Failing here is much easier to debug than a blank interactive panel later.
    blob = json.dumps(payload, ensure_ascii=False, allow_nan=False)

    if path.suffix == ".js":
        path.write_text(
            "/* generated by learnai.export — do not edit by hand */\n"
            "window.LEARNAI_DATA = window.LEARNAI_DATA || {};\n"
            f"window.LEARNAI_DATA[{json.dumps(path.stem)}] = {blob};\n",
            encoding="utf-8",
        )
    else:
        path.write_text(blob, encoding="utf-8")

    if verbose:
        kb = path.stat().st_size / 1024
        print(f"wrote {path}  ({kb:.1f} KB)")
    return path


def export_attention(
    attn: Any,
    tokens: Sequence[str],
    path: str | Path,
    layer_names: Sequence[str] | None = None,
    meta: dict | None = None,
) -> Path:
    """Export attention maps for the attention explorer page.

    attn:   (H, T, T) for one layer, or (L, H, T, T) for a stack, or a dict of
            {layer_name: (H, T, T)}. Batch dim, if present, must be removed first
            (pick one example — the page shows one sequence at a time).
    tokens: T token strings, so the page can label the axes with real text.

    Schema written:
        {"tokens": [...], "layers": [{"name": str, "heads": [[[...]]]}], "meta": {}}
    """
    if isinstance(attn, dict):
        items = list(attn.items())
    else:
        arr = attn.detach().cpu().numpy() if hasattr(attn, "detach") else np.asarray(attn)
        if arr.ndim == 3:  # (H, T, T) — a single layer
            items = [("layer 0", arr)]
        elif arr.ndim == 4:  # (L, H, T, T)
            names = (
                layer_names
                if layer_names is not None
                else [f"layer {i}" for i in range(arr.shape[0])]
            )
            items = list(zip(names, arr, strict=True))
        else:
            raise ValueError(f"expected (H,T,T) or (L,H,T,T), got shape {arr.shape}")

    layers = []
    for name, heads in items:
        h = heads.detach().cpu().numpy() if hasattr(heads, "detach") else np.asarray(heads)
        if h.ndim != 3:
            raise ValueError(f"layer '{name}' must be (H, T, T), got {h.shape}")
        if h.shape[-2:] != (len(tokens), len(tokens)):
            raise ValueError(
                f"layer '{name}' has map shape {h.shape[-2:]} but {len(tokens)} tokens given"
            )
        layers.append({"name": str(name), "heads": _to_list(h)})

    return write_json({"tokens": list(tokens), "layers": layers, "meta": meta or {}}, path)


def export_embeddings(
    vectors: Any,
    labels: Sequence[str],
    path: str | Path,
    method: str = "pca",
    meta: dict | None = None,
) -> Path:
    """Project (N, D) vectors to 2D and export for the embedding-space page.

    `method` is "pca" (fast, linear, distances between far-apart points are
    meaningful) or "tsne" (slow, non-linear, only *local* neighbourhoods mean
    anything — the global layout of a t-SNE plot is not interpretable, a caveat
    almost every blog post gets wrong).
    """
    v = vectors.detach().cpu().numpy() if hasattr(vectors, "detach") else np.asarray(vectors)
    if v.ndim != 2:
        raise ValueError(f"expected vectors shaped (N, D), got {v.shape}")
    if v.shape[0] != len(labels):
        raise ValueError(f"{v.shape[0]} vectors but {len(labels)} labels")

    if method == "pca":
        from sklearn.decomposition import PCA

        reducer = PCA(n_components=2)
        coords = reducer.fit_transform(v)
        explained = float(reducer.explained_variance_ratio_.sum())
    elif method == "tsne":
        from sklearn.manifold import TSNE

        if v.shape[0] < 2:
            raise ValueError("t-SNE needs at least two vectors")
        perplexity = min(30, max(1, v.shape[0] // 4), v.shape[0] - 1)
        coords = TSNE(n_components=2, perplexity=perplexity, init="pca").fit_transform(v)
        explained = None
    else:
        raise ValueError(f"unknown method {method!r}; use 'pca' or 'tsne'")

    return write_json(
        {
            "labels": list(labels),
            "coords": _to_list(coords),
            "method": method,
            "explained_variance": explained,
            "meta": meta or {},
        },
        path,
    )


def export_history(history: Any, path: str | Path, meta: dict | None = None) -> Path:
    """Export a `learnai.train.History` (or plain dict) of training curves."""
    payload = history.to_dict() if hasattr(history, "to_dict") else dict(history)
    return write_json({**_to_list(payload), "meta": meta or {}}, path)


def export_tokenization(
    text: str,
    tokens: Sequence[str],
    path: str | Path,
    ids: Sequence[int] | None = None,
    meta: dict | None = None,
) -> Path:
    """Export a tokenizer's split of some text, for the tokenizer page."""
    return write_json(
        {
            "text": text,
            "tokens": list(tokens),
            "ids": list(ids) if ids is not None else None,
            "n_tokens": len(tokens),
            "n_chars": len(text),
            "chars_per_token": round(len(text) / max(len(tokens), 1), 3),
            "meta": meta or {},
        },
        path,
    )


def export_logits(
    logits: Any,
    vocab: Sequence[str],
    path: str | Path,
    top_k: int = 20,
    context: Sequence[str] | None = None,
    meta: dict | None = None,
) -> Path:
    """Export a next-token distribution (top-k only) for the sampling page.

    Exports raw logits rather than probabilities so the page can apply
    temperature / top-k / top-p itself and you can watch the distribution
    reshape live as you drag the sliders.
    """
    lg = logits.detach().cpu().numpy() if hasattr(logits, "detach") else np.asarray(logits)
    lg = lg.squeeze()
    if lg.ndim != 1:
        raise ValueError(f"expected a 1-D logit vector, got shape {lg.shape}")
    if len(vocab) != lg.shape[0]:
        raise ValueError(f"{lg.shape[0]} logits but {len(vocab)} vocabulary entries")
    if top_k <= 0:
        raise ValueError(f"top_k must be positive, got {top_k}")

    k = min(top_k, lg.shape[0])
    idx = np.argsort(-lg)[:k]
    return write_json(
        {
            "context": list(context) if context else [],
            "tokens": [str(vocab[i]) for i in idx],
            "logits": _to_list(lg[idx]),
            "full_vocab_size": int(lg.shape[0]),
            "meta": meta or {},
        },
        path,
    )
