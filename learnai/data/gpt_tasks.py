"""Controlled task families for studying GPT-style in-context learning.

Each modular-shift episode samples a fresh function ``f_s(x)=(x+s) mod M``.
The model sees input/output demonstrations in its causal context, then answers a
query generated by the same hidden shift.  In the default induction-style task,
the query repeats one demonstrated input: success therefore proves associative
retrieval from context, without pretending the tiny model learned arithmetic.
"""

from __future__ import annotations

from typing import Protocol

import torch

BOS_TOKEN_ID = 0
ARROW_TOKEN_ID = 1
SEPARATOR_TOKEN_ID = 2
NUMBER_TOKEN_OFFSET = 3
IGNORE_INDEX = -100


class _CausalModel(Protocol):
    training: bool

    def eval(self): ...

    def train(self, mode: bool = True): ...

    def __call__(self, idx: torch.Tensor): ...


def make_modular_shift_batch(
    batch_size: int,
    shots: int,
    modulus: int = 7,
    *,
    generator: torch.Generator | None = None,
    device: str | torch.device | None = None,
    shuffle_labels: bool = False,
) -> tuple[torch.Tensor, torch.Tensor]:
    """Build causal episodes and answer-only targets.

    A row with two demonstrations is encoded as::

        BOS x₁ ARROW y₁ SEP x₂ ARROW y₂ SEP query ARROW

    Integers occupy ids ``3 .. 3+modulus-1``.  When demonstrations exist, the
    query repeats one of their inputs (chosen independently per row), making
    this a controlled induction/lookup task.  Targets are ``-100`` except at the
    final ``ARROW`` position.  Its answer is intentionally absent from the input,
    exactly like a completion prompt.
    """
    if batch_size <= 0:
        raise ValueError(f"batch_size must be positive, got {batch_size}")
    if shots < 0:
        raise ValueError(f"shots must be non-negative, got {shots}")
    if modulus < 2:
        raise ValueError(f"modulus must be at least 2, got {modulus}")

    shifts = torch.randint(modulus, (batch_size, 1), generator=generator)
    values = torch.randint(modulus, (batch_size, shots + 1), generator=generator)
    if shots:
        query_columns = torch.randint(shots, (batch_size,), generator=generator)
        values[:, -1] = values[torch.arange(batch_size), query_columns]
    answers = (values + shifts) % modulus

    shown_answers = answers[:, :shots].clone()
    if shuffle_labels and shots:
        # A non-zero modular offset guarantees every displayed label is wrong,
        # including for batch_size=1.  Uniform labels remain uniform in
        # distribution; prompt length, query, and the correct query target stay
        # fixed while demonstration pair information is destroyed.
        offsets = torch.randint(
            1, modulus, shown_answers.shape, generator=generator, dtype=shown_answers.dtype
        )
        shown_answers = (shown_answers + offsets) % modulus

    sequence_length = 4 * shots + 3
    inputs = torch.full((batch_size, sequence_length), SEPARATOR_TOKEN_ID, dtype=torch.long)
    targets = torch.full_like(inputs, IGNORE_INDEX)
    inputs[:, 0] = BOS_TOKEN_ID

    for demonstration in range(shots):
        start = 1 + 4 * demonstration
        inputs[:, start] = values[:, demonstration] + NUMBER_TOKEN_OFFSET
        inputs[:, start + 1] = ARROW_TOKEN_ID
        inputs[:, start + 2] = shown_answers[:, demonstration] + NUMBER_TOKEN_OFFSET
        inputs[:, start + 3] = SEPARATOR_TOKEN_ID

    query_start = 1 + 4 * shots
    inputs[:, query_start] = values[:, -1] + NUMBER_TOKEN_OFFSET
    inputs[:, query_start + 1] = ARROW_TOKEN_ID
    targets[:, query_start + 1] = answers[:, -1] + NUMBER_TOKEN_OFFSET

    if device is not None:
        inputs = inputs.to(device)
        targets = targets.to(device)
    return inputs, targets


@torch.inference_mode()
def modular_shift_accuracy(
    model: _CausalModel,
    shots: int,
    episodes: int = 512,
    modulus: int = 7,
    device: str | torch.device = "cpu",
    shuffle_labels: bool = False,
    *,
    generator: torch.Generator | None = None,
) -> float:
    """Measure query accuracy without updating parameters or model mode."""
    if episodes <= 0:
        raise ValueError(f"episodes must be positive, got {episodes}")
    if shots < 0:
        raise ValueError(f"shots must be non-negative, got {shots}")
    if modulus < 2:
        raise ValueError(f"modulus must be at least 2, got {modulus}")

    was_training = model.training
    model.eval()
    correct = 0
    seen = 0
    try:
        for start in range(0, episodes, 256):
            batch_size = min(256, episodes - start)
            inputs, targets = make_modular_shift_batch(
                batch_size,
                shots,
                modulus,
                generator=generator,
                device=device,
                shuffle_labels=shuffle_labels,
            )
            output = model(inputs)
            logits = output[0] if isinstance(output, tuple) else output
            predictions = logits[:, -1].argmax(dim=-1)
            correct += int((predictions == targets[:, -1]).sum())
            seen += batch_size
    finally:
        model.train(was_training)
    return correct / seen
